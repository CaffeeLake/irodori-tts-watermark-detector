/**
 * Real-browser end-to-end test: loads web/index.html in headless Firefox, feeds it the
 * .webm clips from the repo root plus negative controls, and checks the verdicts.
 *
 * This is the authoritative test of the shipped artefact — WebAudio decoding,
 * onnxruntime-web's WebAssembly backend and the worker are all exercised for real.
 *
 *   node test/browser.test.mjs            # all clips
 *   BROWSER=chromium node test/browser.test.mjs
 */
import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';

import { startServer } from '../tools/serve.mjs';
import { THRESHOLDS } from '../web/src/detector.js';

const ROOT = path.resolve(import.meta.dirname, '..');
const WINDOW = process.env.WINDOW || '10';

const { firefox, chromium, webkit } = await import('playwright');
const browserType = { firefox, chromium, webkit }[process.env.BROWSER || 'firefox'];

const server = await startServer({ port: Number(process.env.PORT || 0) });

const failures = [];
const check = (name, cond, detail) => {
  console.log(`  ${cond ? 'PASS' : 'FAIL'}  ${name}${detail ? ` — ${detail}` : ''}`);
  if (!cond) failures.push(name);
};

const browser = await browserType.launch();
const page = await browser.newPage();
page.on('console', (m) => { if (m.type() === 'error') console.error('   [page error]', m.text()); });
page.on('pageerror', (e) => console.error('   [page exception]', e.message));

await page.goto(`${server.url}/index.html`);
await page.waitForFunction(() => window.__detector && window.__detector.ready(), null, { timeout: 120000 });
await page.evaluate(() => window.__detector.ready());

const env = await page.evaluate(() => document.getElementById('env').textContent);
console.log(`\nbrowser=${process.env.BROWSER || 'firefox'}  ${env}\n`);

async function analyse(bytes, opts = {}) {
  const payload = Array.from(bytes);
  return page.evaluate(async ({ payload, opts }) => {
    const buf = new Uint8Array(payload).buffer;
    const r = await window.__detector.analyseBuffer(buf, opts);
    if (r.type === 'error') return { error: r.message };
    return {
      verdict: r.result.verdict,
      match: r.result.match,
      nullMatch: r.result.nullMatch,
      margin: r.result.margin,
      pValue: r.result.pValue,
      structure: r.result.structure,
      frames: r.result.frames,
      shift: r.result.shift,
      ascii: r.result.blind.ascii,
      symbolAgreement: r.result.symbolAgreement,
      inferMs: r.inferMs,
    };
  }, { payload, opts });
}

const fmt = (r) => `verdict=${r.verdict} match=${r.match.toFixed(3)} null=${r.nullMatch.toFixed(3)} `
  + `margin=${r.margin.toFixed(3)} p=${r.pValue.toExponential(2)} struct=${r.structure.toFixed(3)} `
  + `frames=${r.frames} shift=${r.shift} blind=${r.ascii} sym=${r.symbolAgreement}/21 `
  + `(${(r.inferMs / 1000).toFixed(1)}s)`;

/* ----------------------------------------------- positives: sample audio ----- */
// Generated by tools/make_samples.py: real watermarks on a synthesised carrier, so the
// suite does not depend on any particular file being dropped into the repo.
const SAMPLES = path.join(ROOT, 'test', 'samples');
const clips = ['44k1_watermarked.wav', '44k1_watermarked.webm']
  .filter((f) => existsSync(path.join(SAMPLES, f)));
console.log('positives (44.1 kHz watermarked samples):');
if (!clips.length) {
  console.log('    SKIP: test/samples is empty — run `npm run samples` first.');
}

for (const clip of clips) {
  const bytes = readFileSync(path.join(SAMPLES, clip));
  const r = await analyse(bytes, { window: WINDOW });
  if (r.error) { check(clip, false, r.error); continue; }
  console.log(`    ${clip}: ${fmt(r)}`);
  check(`${clip} -> detected`, r.verdict === 'detected', `got ${r.verdict}`);
  check(`${clip} -> p <= ${THRESHOLDS.detectP}`, r.pValue <= THRESHOLDS.detectP,
    `p=${r.pValue.toExponential(2)}`);
  check(`${clip} -> margin >= ${THRESHOLDS.detectMargin}`, r.margin >= THRESHOLDS.detectMargin,
    `margin=${r.margin.toFixed(3)}`);
  check(`${clip} -> word aligned to file start`, r.shift === 0, `shift=${r.shift}`);
}

/* ------------------------------------------------------- negative controls --- */
console.log('\nnegative controls (synthesised in-page):');
const NEGATIVES = {
  'white-noise': `(() => { let s = 7; const n = 48000 * ${Number(WINDOW) + 2};
     const a = new Float32Array(n);
     for (let i = 0; i < n; i++) { s = (s * 1103515245 + 12345) & 0x7fffffff; a[i] = (s / 0x7fffffff - 0.5) * 0.2; }
     return a; })()`,
  'sine-440': `(() => { const n = 48000 * ${Number(WINDOW) + 2}; const a = new Float32Array(n);
     for (let i = 0; i < n; i++) a[i] = 0.3 * Math.sin(2 * Math.PI * 440 * i / 48000); return a; })()`,
  'chirp': `(() => { const n = 48000 * ${Number(WINDOW) + 2}; const a = new Float32Array(n);
     for (let i = 0; i < n; i++) { const t = i / 48000; a[i] = 0.3 * Math.sin(2 * Math.PI * (200 + 300 * t) * t); } return a; })()`,
};

for (const [name, expr] of Object.entries(NEGATIVES)) {
  const r = await page.evaluate(async ({ expr, win }) => {
    // eslint-disable-next-line no-eval
    const pcm = eval(expr);
    const wav = (() => {                       // minimal 32-bit float WAV container
      const n = pcm.length, b = new ArrayBuffer(44 + n * 4), v = new DataView(b);
      const str = (o, s) => { for (let i = 0; i < s.length; i++) v.setUint8(o + i, s.charCodeAt(i)); };
      str(0, 'RIFF'); v.setUint32(4, 36 + n * 4, true); str(8, 'WAVEfmt ');
      v.setUint32(16, 16, true); v.setUint16(20, 3, true); v.setUint16(22, 1, true);
      v.setUint32(24, 48000, true); v.setUint32(28, 48000 * 4, true);
      v.setUint16(32, 4, true); v.setUint16(34, 32, true);
      str(36, 'data'); v.setUint32(40, n * 4, true);
      new Float32Array(b, 44).set(pcm);
      return b;
    })();
    const res = await window.__detector.analyseBuffer(wav, { window: win, earlyStop: false });
    if (res.type === 'error') return { error: res.message };
    const r = res.result;
    return {
      verdict: r.verdict, match: r.match, nullMatch: r.nullMatch, margin: r.margin,
      pValue: r.pValue, structure: r.structure, frames: r.frames, shift: r.shift,
      ascii: r.blind.ascii, symbolAgreement: r.symbolAgreement, inferMs: res.inferMs,
    };
  }, { expr, win: WINDOW });

  if (r.error) { check(name, false, r.error); continue; }
  console.log(`    ${name}: ${fmt(r)}`);
  check(`${name} -> not detected`, r.verdict !== 'detected', `got ${r.verdict}`);
  check(`${name} -> no watermark structure`, r.structure < THRESHOLDS.structurePresent,
    `structure=${r.structure.toFixed(3)}`);
}

await browser.close();
await server.close();

console.log(`\n${failures.length ? `FAILED (${failures.length}): ${failures.join(', ')}` : 'all browser checks passed'}`);
process.exit(failures.length ? 1 : 0);
